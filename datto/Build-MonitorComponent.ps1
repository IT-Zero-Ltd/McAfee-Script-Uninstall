<#
.SYNOPSIS
  Embeds mcafee_detect.ps1 into datto/McAfeePresent-Monitor.ps1 and updates its pinned SHA256.

.DESCRIPTION
  Datto RMM monitor components can't carry attached files, so the monitor carries the detection script
  inside itself as base64. Run this whenever mcafee_detect.ps1 changes, commit the result, then paste the
  regenerated McAfeePresent-Monitor.ps1 into the Datto component and re-push the monitoring policy.

  Works in Windows PowerShell 5.1 and PowerShell 7.

.EXAMPLE
  powershell.exe -ExecutionPolicy Bypass -File .\datto\Build-MonitorComponent.ps1
#>
[CmdletBinding()]
param(
    [string]$DetectScript = (Join-Path (Split-Path -Parent (Split-Path -Parent $MyInvocation.MyCommand.Path)) 'mcafee_detect.ps1'),
    [string]$MonitorScript = (Join-Path (Split-Path -Parent $MyInvocation.MyCommand.Path) 'McAfeePresent-Monitor.ps1')
)
$ErrorActionPreference = 'Stop'

$bytes = [IO.File]::ReadAllBytes((Resolve-Path -LiteralPath $DetectScript).Path)
$sha = [System.Security.Cryptography.SHA256]::Create()
$hash = ([BitConverter]::ToString($sha.ComputeHash($bytes))) -replace '-', ''

# Base64 in 100-character lines inside a single-quoted here-string (base64 has no quote characters).
$b64 = [Convert]::ToBase64String($bytes)
$lines = for ($i = 0; $i -lt $b64.Length; $i += 100) { $b64.Substring($i, [Math]::Min(100, $b64.Length - $i)) }

$monitorPath = (Resolve-Path -LiteralPath $MonitorScript).Path
$text = [IO.File]::ReadAllText($monitorPath)
$nl = "`n"; if ($text.Contains("`r`n")) { $nl = "`r`n" }

$begin = '# BEGIN EMBEDDED mcafee_detect.ps1 (generated by Build-MonitorComponent.ps1 - do not edit)'
$end   = '# END EMBEDDED mcafee_detect.ps1'
$start = $text.IndexOf($begin)
$stop  = $text.IndexOf($end)
if ($start -lt 0 -or $stop -lt $start) { throw "Embedded-block markers not found in $monitorPath" }

$block = $begin + $nl + '$EmbeddedDetectBase64 = @''' + $nl + ($lines -join $nl) + $nl + '''@' + $nl
$text = $text.Substring(0, $start) + $block + $text.Substring($stop)

$pattern = "\`$ExpectedSha256 = '[0-9A-Fa-f]*'"
if ($text -notmatch $pattern) { throw "`$ExpectedSha256 line not found in $monitorPath" }
$text = [regex]::Replace($text, $pattern, ("`$ExpectedSha256 = '{0}'" -f $hash))

[IO.File]::WriteAllText($monitorPath, $text, (New-Object System.Text.UTF8Encoding($false)))
Write-Output ("Embedded {0} ({1} bytes, SHA256 {2}) into {3}" -f (Split-Path -Leaf $DetectScript), $bytes.Length, $hash, $monitorPath)
